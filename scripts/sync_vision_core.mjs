// Deterministic static CommonJS packaging. Source bodies are preserved byte-for-byte;
// no eval, string rewriting of algorithms, or remote executable code.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { createRequire } from "node:module";
const root = path.resolve(import.meta.dirname, "..");
const upstream = path.resolve(
  process.env.VISION_SOURCE || path.join(root, "../chesspuzzle"),
);
const core = path.join(upstream, "services/vision/core");
const sha = (value) => crypto.createHash("sha256").update(value).digest("hex");
const update = process.argv.includes("--update");
const checkSource = process.argv.includes("--source") || update;
const lockPath = path.join(root, "lib/vision/core-lock.json");
if (!checkSource) {
  const lock = JSON.parse(fs.readFileSync(lockPath));
  for (const [file, hash] of Object.entries(lock.outputs))
    if (sha(fs.readFileSync(path.join(root, file))) !== hash)
      throw Error("Generated vision drift: " + file);
  console.log("PASS vision output/model hashes, core " + lock.coreVersion);
  process.exit(0);
}
const names = [
  "recognizer-core",
  "task-controller",
  "crypto-utils",
  "board-detector",
  "perspective",
  "quad-detector",
  "coordinate-detector",
  "coordinate-templates",
  "inner-coordinates",
  "qimi-piece-matcher",
  "qimi-piece-templates",
  "turn-detector",
  "protocol",
  "piece-classifier",
  "fen-optimizer",
  "consensus-engine",
  "image-context",
  "default-context",
];
const sourcePath = (name) =>
  path.join(
    core,
    ["image-context", "default-context"].includes(name)
      ? "../" + name + ".js"
      : name + ".js",
  );
const sources = Object.fromEntries(
  names.map((name) => [name, fs.readFileSync(sourcePath(name), "utf8")]),
);
sources.chess = fs.readFileSync(path.join(upstream, "utils/chess.js"), "utf8");
const external = new Set([
  "./adapters/web-adapter",
  "./adapters/node-adapter",
  "./adapters/wechat-adapter",
  "../../../utils/chess",
  "../../utils/chess",
  "crypto",
]);
for (const [name, body] of Object.entries(sources)) {
  for (const match of body.matchAll(/require\(['"]([^'"]+)['"]\)/g)) {
    if (!external.has(match[1]) && !sources[match[1].replace(/^\.\//, "")])
      throw Error("Missing browser dependency in " + name + ": " + match[1]);
  }
}
const req = createRequire(import.meta.url),
  exportsFor = {};
for (const name of names) exportsFor[name] = Object.keys(req(sourcePath(name)));
const output = {};
output["lib/vision/core-generated.js"] =
  '// GENERATED by scripts/sync_vision_core.mjs. Edit chesspuzzle source instead.\nimport { WebAdapter } from "./web-adapter.js";\nconst factories = {\n' +
  Object.entries(sources)
    .map(
      ([name, body]) =>
        JSON.stringify(name) +
        ": function(module,exports,require){\n" +
        body +
        "\n}",
    )
    .join(",\n") +
  '\n};\nconst cache = {};\nexport function getModule(name) {\n if(cache[name]) return cache[name].exports;\n const factory = factories[name]; if(!factory) throw Error("Unsupported vision dependency: " + name);\n const module = cache[name] = {exports:{}};\n factory(module,module.exports, request => {\n if(request === "./adapters/web-adapter") return {WebAdapter};\n if(request === "../../../utils/chess" || request === "../../utils/chess") return getModule("chess");\n return getModule(request.replace(/^\\.\\//, ""));\n });\n return module.exports;\n}\n';
for (const name of names)
  output["lib/vision/" + name + ".js"] =
    '// GENERATED. See core-lock.json.\nimport { getModule } from "./core-generated.js";\nexport const { ' +
    exportsFor[name].join(", ") +
    " } = getModule(" +
    JSON.stringify(name) +
    ");\n";
output["lib/vision/chess.js"] =
  '// GENERATED. See core-lock.json.\nimport { getModule } from \"./core-generated.js\";\nexport const { Chess } = getModule(\"chess\");\nexport default Chess;\n';
for (const name of ["chess-cnn.wasm", "chessimg2pos_weights.bin"])
  output["models/" + name] = fs.readFileSync(
    path.join(upstream, "assets/models", name),
  );
const lock = {
  coreVersion: "2026.10.14.2",
  protocolVersion: 1,
  buildToolVersion: 2,
  sourceProject: "chesspuzzle",
  sourceTreeHash: sha(JSON.stringify(sources)),
  sources: Object.fromEntries(
    Object.entries(sources).map(([name, body]) => [name, sha(body)]),
  ),
  outputs: Object.fromEntries(
    Object.entries(output).map(([file, body]) => [file, sha(body)]),
  ),
};
if (update) {
  for (const [file, body] of Object.entries(output))
    fs.writeFileSync(path.join(root, file), body);
  fs.writeFileSync(lockPath, JSON.stringify(lock, null, 2) + "\n");
  fs.writeFileSync(
    path.join(core, "extension-core-lock.json"),
    JSON.stringify(
      {
        coreVersion: lock.coreVersion,
        sourceTreeHash: lock.sourceTreeHash,
        buildToolVersion: lock.buildToolVersion,
        extensionOutputs: lock.outputs,
      },
      null,
      2,
    ) + "\n",
  );
} else {
  const saved = JSON.parse(fs.readFileSync(lockPath));
  if (saved.sourceTreeHash !== lock.sourceTreeHash)
    throw Error(
      "Upstream vision changed. Run sync --update and both runtime suites.",
    );
  for (const [file, hash] of Object.entries(lock.outputs))
    if (sha(fs.readFileSync(path.join(root, file))) !== hash)
      throw Error("Vision drift: " + file);
}
console.log(
  "PASS shared vision source and browser build " +
    lock.sourceTreeHash.slice(0, 12),
);
