import assert from 'node:assert/strict';
import { GameAnalyzer } from '../engine/game-analyzer.js';
import { ChessBoard } from '../engine/chess-core.js';
let searches=0, loads=0;
const sf={engineKey:'split-test',isReady:true,stop(){},async evaluate(fen,depth){
 searches++;
 const board=new ChessBoard(fen), move=board.getLegalMoves()[0];
 return {scoreCp:0,score:'0.00',depth,bestMove:move,lines:[],pv:move?[move.uci]:[]};
}};
const maia={modelKey:'23m-test',isReady:false,async initialize(){loads++;throw new Error('Model intentionally unavailable');},async predict(){return null;}};
const moves=GameAnalyzer.parsePgn('1. e4 e5 2. Nf3 Nc6 1/2-1/2');
const analyzer=new GameAnalyzer(sf,maia);
const core=await analyzer.analyzeGame(moves,{engineOnly:true,forceRefresh:true});
assert.equal(loads,0,'Scoring cannot initialize or wait for Maia');
assert.equal(searches,5);
assert.equal(core.engineOnly,true);
assert.equal(GameAnalyzer.isValidReviewCache(core),true,'Maia-free core reports are valid');
assert.equal(core.positionEvaluations.length,5);
maia.modelKey='79m-test';
const otherModel=await analyzer.analyzeGame(moves,{engineOnly:true,elo:2200});
assert.equal(searches,5,'Changing model or rating reuses the independent scoring cache');
assert.equal(otherModel.accuracyWhite,core.accuracyWhite);
const enriched=await analyzer.analyzeGame(moves,{baseReview:core,forceRefresh:true});
assert.equal(searches,5,'Intuition pass reuses every original SF evaluation');
assert.equal(enriched.accuracyWhite,core.accuracyWhite);
assert.equal(await GameAnalyzer.getCachedReview(enriched.gameKey),null,'Unavailable intuition must remain retryable, not cached as complete');
const obsolete = structuredClone(enriched);
obsolete.positionEvaluations[0].scoreCp = 500;
obsolete.accuracyWhite = 1;
obsolete.allMoves[0].maiaTopSan = 'e4';
await GameAnalyzer.saveCachedReview(enriched.gameKey, obsolete);
const freshBase = await analyzer.analyzeGame(moves,{baseReview:core});
assert.equal(freshBase.accuracyWhite,core.accuracyWhite,'Old intuition cache cannot overwrite freshly calculated scores');
assert.equal(searches,5,'Rejecting stale intuition still reuses the current scoring snapshot');
const calls=searches;
await analyzer.analyzeGame(GameAnalyzer.parsePgn('1. d4 d5'),{engineOnly:true,baseReview:core,forceRefresh:true});
assert.equal(searches,calls+3,'A different game cannot borrow old evaluations');
console.log('Split review: scores without Maia, model-independent cache, score reuse and stale-game isolation passed');
