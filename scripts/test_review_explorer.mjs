import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { REVIEW_QUALITIES, moveQuality, reviewCounts, selectReviewMoves, canPractice, intuitionKind } from '../engine/review-policy.js';
import { ReviewPractice } from '../analysis/review-practice.js';
const move = (ply, lossCp, extra = {}) => ({ ply, turn: ply % 2 ? 'w' : 'b', severity: 'good', lossCp, uci: 'a7a8n', bestUci: 'a7a8q', fenBefore: 'fixture', bestSan: 'a8=Q', ...extra });
const moves = [move(1, 0, { uci: 'a7a8q', isBookMove: true }), move(2, 20), move(3, 40), move(4, 100, { divergenceType: 'intuition_trap', divergenceStatus: 'confirmed' }), move(5, 200), move(6, null, { severity: 'unknown' }), move(7, 0, { isOnlyLegalMove: true }), move(8, 0, { uci: 'a7a8q', divergenceType: 'beyond_intuition', divergenceStatus: 'confirmed' }), move(10, 0, { divergenceType: 'beyond_intuition', isCombinationFollowup: true }), move(11, 0, { divergenceType: 'intuition_trap', divergenceStatus: 'unconfirmed' })];
assert.equal(moveQuality(moves[1]), 'good', 'Low loss alone is not Best, including different promotions');
assert.equal(moveQuality(move(1, 0, { severity: 'unknown', uci: 'a7a8q' })), 'unknown');
assert.equal(moveQuality(move(1, 0, { severity: undefined })), 'unknown');
assert.equal(moveQuality(move(1, 0, { accuracy: null })), 'unknown', 'An explicit missing evaluation cannot be hidden by a default zero loss');
const counts = reviewCounts(moves);
for (const side of ['w', 'b']) assert.equal(REVIEW_QUALITIES.reduce((sum, key) => sum + counts[side][key], 0), counts[side].total, 'Quality counts partition each side exactly');
assert.equal(counts.w.book, 1); assert.equal(counts.b.trap, 1); assert.equal(counts.b.beyond, 1);
assert.deepEqual(selectReviewMoves(moves, 'b', 'quality:mistake').map(m => m.ply), [4]);
assert.deepEqual(selectReviewMoves(moves, 'b', 'trap').map(m => m.ply), [4]);
assert.deepEqual(selectReviewMoves(moves, 'all', 'beyond').map(m => m.ply), [8], 'Combination continuations do not inflate filters');
assert.deepEqual(selectReviewMoves(moves, 'all', 'all').map(m => m.ply), [4, 5, 8]);
assert.equal(intuitionKind(moves.at(-1)), null);
assert.equal(intuitionKind(move(1, null, { severity: 'unknown', divergenceType: 'intuition_trap', divergenceStatus: 'confirmed' })), null, 'Missing engine evidence cannot become a teaching claim');
assert(!canPractice(moves[5]) && !canPractice(moves[6]));
assert(canPractice(moves[2]) && canPractice(moves[7]));

const dom = new JSDOM('<div id="practice-panel"></div>', { url: 'https://4chess.cc/analysis/' });
globalThis.window = dom.window; globalThis.document = dom.window.document;
dom.window.HTMLElement.prototype.scrollIntoView = () => {};
let searches = 0;
const app = { gameEpoch: 1, positionAnalysis: { cancel() {}, clearOverlays() {} }, el: { boardStatusText: document.createElement('span') }, goToPly() {}, stockfish: { async evaluate(_fen, depth) { searches++; return depth === 14 ? { scoreCp: 100, depth: 14, bestMove: { uci: 'a7a8q', san: 'a8=Q' } } : { scoreCp: -80, depth: 13 }; }, stop() {} }, boardUI: { setPosition() {}, clearArrows() {} } };
const practice = new ReviewPractice(app);
const queue = [moves[2], moves[3], moves[4]];
practice.start(queue[0], { queue });
await practice.submit({}, 'after');
assert.equal(app.practiceResults.get(3).status, 'independent');
practice.next(); await practice.hint();
assert.equal(app.practiceResults.get(4).status, 'hint_used', 'A hint alone is not a successful retry');
const afterHintSearches = searches;
await practice.submit({}, 'after');
assert.equal(searches, afterHintSearches + 1, 'Hint and grading reuse the same deep reference; only the child position is searched');
assert.equal(app.practiceResults.get(4).status, 'hinted');
practice.next(); await practice.reveal(); await practice.submit({}, 'after');
assert.equal(app.practiceResults.get(5).status, 'revealed', 'Viewing the answer permanently prevents an independent-success claim for this attempt');
practice.next();
assert(!practice.active); assert.match(document.getElementById('practice-panel').textContent, /Independent 1|独立找到 1/);
practice.stop(); assert(document.getElementById('practice-panel').hidden);
app.stockfish.evaluate = async () => ({ scoreCp: 100, depth: 2 });
practice.start(queue[0]); await practice.submit({}, 'after');
assert.equal(app.practiceResults.get(3).status, 'uncertain');
assert.equal(practice.controls.next.disabled, true, 'A shallow result cannot pass a practice question');
practice.stop();
let release, lateUpdates = 0;
app.stockfish.evaluate = () => { searches++; return new Promise(resolve => { release = resolve; }); };
app.boardUI.setPosition = () => { lateUpdates++; };
practice.start(queue[0]); const before = searches;
const pending = practice.submit({}, 'after'); app.gameEpoch++;
release({ scoreCp: 100, depth: 14 }); await pending;
assert.equal(searches, before + 1, 'Changing game cancels grading before the second search');
assert.equal(lateUpdates, 0, 'Late grade cannot replace another game board');
practice.stop(); dom.window.close();
console.log('PASS review explorer: exhaustive side counts, overlapping labels, strict unknowns, promotion identity, confirmed intuition, deduplication, practice provenance and stale-game isolation.');
